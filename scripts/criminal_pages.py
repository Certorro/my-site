def rich(s):
    """Экранирует текст и превращает **акцент** в <strong>акцент</strong>."""
    return re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", esc(s))


def plain(s):
    """Текст без разметки акцентов — для мета-тегов и JSON-LD."""
    return s.replace("**", "")


